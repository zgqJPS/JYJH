    payload_bytes = base64.b64decode(PAYLOAD)
    decompressed = zlib.decompress(payload_bytes)
    zf = zipfile.ZipFile(io.BytesIO(decompressed))

    updated_files = []
    for name in zf.namelist():
        target = os.path.join(script_dir, name)
        target_dir = os.path.dirname(target)
        os.makedirs(target_dir, exist_ok=True)
        if os.path.exists(target):
            backup = target + ".bak2"
            shutil.copy2(target, backup)
            print(f"  备份: {name} -> {name}.bak2")
        with open(target, "wb") as f:
            f.write(zf.read(name))
        updated_files.append(name)
        print(f"  更新: {name}")
    print(f"\n  共更新 {len(updated_files)} 个文件")

    # 2. 验证
    print("\n[2/3] 验证更新...")
